# ── Paridad JS: las regex, keywords y mensajes viven en Python; el port JS los
#    embebe como TA_SPEC entre marcadores. `python test_assess.py --sync-js` lo regenera.
JS_CORE = os.path.join(HERE, "promptometer-core.js")
SPEC_START, SPEC_END = "/* <ta-spec> generated by test_assess.py --sync-js; do not edit */", "/* </ta-spec> */"


def build_js_spec():
    import re
    patterns = {}
    for name, val in sorted(vars(pc).items()):
        if name.startswith("_RE_TA_") and isinstance(val, re.Pattern):
            patterns[name[len("_RE_TA_"):]] = {
                "source": val.pattern,
                "flags": "i" if val.flags & re.IGNORECASE else "",
            }
    return {
        "patterns": patterns,
        "softwareKeywords": pc._TA_SOFTWARE_KEYWORDS,
        "researchKeywords": pc._TA_RESEARCH_KEYWORDS,
        "deepKeywords": pc._TA_DEEP_KEYWORDS,
        "fastKeywords": pc._TA_FAST_KEYWORDS,
        "moduleStoplist": sorted(pc._TA_MODULE_STOPLIST),
        "severityRank": pc._TA_SEVERITY_RANK,
        "messages": pc._TA_MESSAGES,
    }


def _render_spec_block():
    body = json.dumps(build_js_spec(), ensure_ascii=False, indent=2)
    body = "\n".join("  " + line for line in body.splitlines()).lstrip()
    return "{}\n  const TA_SPEC = {};\n  {}".format(SPEC_START, body, SPEC_END)


def _split_js():
    with open(JS_CORE, encoding="utf-8") as fh:
        src = fh.read()
    i, j = src.index(SPEC_START), src.index(SPEC_END) + len(SPEC_END)
    return src, i, j


def sync_js():
    src, i, j = _split_js()
    with open(JS_CORE, "w", encoding="utf-8", newline="") as fh:
        fh.write(src[:i] + _render_spec_block() + src[j:])


def test_js_spec_in_sync():
    src, i, j = _split_js()
    assert src[i:j] == _render_spec_block(), "TA_SPEC desincronizado: corre `python test_assess.py --sync-js`"


def _parity_jobs():
    """Fixtures + corpus aleatorio determinista (acentos, unicode, voz, rutas) para cazar
    diferencias entre `re` de Python y RegExp de JS."""
    import random
    rnd = random.Random(7)
    parts = ["únicamente", "añade", "Añade", "código", "está mal", "así no", "reviértelo", "función",
             "`get_user()`", "src/auth.py", "auth.py", "yunta barra intent punto py", "clase Foo", "CamelCase",
             "snake_case_var", "KeyError", "sin romper tests", "en viñetas", "cátedra", "audio", "tabla",
             "causa raíz", "rápido", "explica", "no,", "esperaba 404", "js/app.js", "analyzer", "naïve",
             "日本語", "🤖", "Привет", "e.g.", "v1.0", "y/o", "http://x.com/a", "ñandú", "über_func()",
             "deshaz", "continúa", "dale", "arreglalo", "crea", "nuevo", "README.md", "punto js"]
    known = ["js/analyzer.js", "js/app.js", "server.js", "src/auth.py", "über/ñandú.py", "README.md"]
    ctxs = [{}, {"turn": 2}, {"known_files": known}, {"known_files": known, "turn": 3, "lang": "en"},
            {"is_voice": True}]
    jobs = [(c["prompt"], c["context"]) for c in _load_cases()]
    for _ in range(300):
        text = " ".join(rnd.choice(parts) for _ in range(rnd.randint(1, 9)))
        jobs.append((text, rnd.choice(ctxs)))
    return jobs


def test_js_parity():
    """Si hay node disponible, el port JS debe producir exactamente lo mismo que Python."""
    import shutil
    import tempfile
    node = shutil.which("node")
    if not node:
        return
    jobs = _parity_jobs()
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as fh:
        json.dump(jobs, fh, ensure_ascii=False)
    try:
        script = (
            "const pc=require(process.argv[1]);const jobs=JSON.parse(require('fs').readFileSync(process.argv[2],'utf8'));"
            "process.stdout.write(JSON.stringify(jobs.map(([t,c])=>pc.assess(t,c))));"
        )
        out = subprocess.run([node, "-e", script, JS_CORE, fh.name], capture_output=True, text=True,
                             encoding="utf-8", check=True)
    finally:
        os.unlink(fh.name)
    for (text, ctx), js in zip(jobs, json.loads(out.stdout)):
        py = pc.assess(text, ctx)
        diffs = {k: (py[k], js.get(k)) for k in py if py[k] != js.get(k)}
        assert not diffs, "{!r} {}: py vs js {}".format(text[:60], ctx, diffs)


def _cli(*args):
    env = dict(os.environ, PYTHONIOENCODING="utf-8")
    out = subprocess.run([sys.executable, os.path.join(HERE, "promptometer_core.py")] + list(args),
                         capture_output=True, text=True, encoding="utf-8", env=env, check=True)
    return json.loads(out.stdout)


def test_cli_assess_json():
    r = _cli("assess", "reviértelo, te equivocaste", "--turn", "2")
    assert r["correction"] is True and r["turn"] == 2


def test_cli_files_from_git():
    r = _cli("assess", "edita auth/inexistente.py", "--files-from", "git", "--compact")
    assert r["grounded"] is True
    assert r["targets"]["missing"] == ["auth/inexistente.py"]


